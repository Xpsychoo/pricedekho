import { DEMO_CATEGORIES, DEMO_CREATED_AT, DEMO_PRODUCTS, DEMO_PROVIDER_ID, DEMO_STORES } from "@pricedekho/shared/demo";

const lit = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const num = (v: number | null) => (v === null ? "null" : String(v));

/**
 * Generates supabase/seed.sql from the DEMO catalog. Output is deterministic
 * so a test can verify the committed file is up to date.
 */
export function generateSeedSql(): string {
  const lines: string[] = [
    "-- =====================================================================",
    "-- DEMO SEED DATA — NOT REAL PRICES",
    "-- Generated by `pnpm seed:generate` from packages/shared/src/demo/catalog.ts.",
    "-- Do not edit by hand. All stores are fictional (.example domains), all",
    "-- offers have source = 'demo' and last_checked_at = null, and no price",
    "-- history is seeded. See README → \"Removing demo data\" before launch.",
    "-- =====================================================================",
    "",
    "begin;",
    "",
    "insert into public.categories (id, slug, name, description, created_at) values",
    DEMO_CATEGORIES.map((c) => `  (${lit(c.id)}, ${lit(c.slug)}, ${lit(c.name)}, ${lit(c.description)}, ${lit(DEMO_CREATED_AT)})`).join(",\n") +
      "\non conflict (slug) do nothing;",
    "",
    "insert into public.stores (id, slug, name, website_url, is_demo, active, created_at) values",
    DEMO_STORES.map((s) => `  (${lit(s.id)}, ${lit(s.slug)}, ${lit(s.name)}, ${lit(s.websiteUrl)}, true, true, ${lit(DEMO_CREATED_AT)})`).join(",\n") +
      "\non conflict (slug) do nothing;",
    "",
    "insert into public.products (id, category_id, slug, name, brand, model, description, specifications, variant_attributes, variant_key, is_demo, created_at, updated_at) values",
    DEMO_PRODUCTS.map(
      (p) =>
        `  (${lit(p.id)}, ${lit(p.categoryId)}, ${lit(p.slug)}, ${lit(p.name)}, ${lit(p.brand)}, ${lit(p.model)}, ${lit(p.description)}, ` +
        `${json(p.specifications)}, ${json(p.variantAttributes)}, ${lit(p.variantKey)}, true, ${lit(DEMO_CREATED_AT)}, ${lit(DEMO_CREATED_AT)})`,
    ).join(",\n") + "\non conflict (slug) do nothing;",
    "",
    "insert into public.offers (id, product_id, store_id, provider_id, external_product_id, variant_key, product_url, seller_name, price_paise, original_price_paise, availability, source, last_checked_at) values",
    DEMO_PRODUCTS.flatMap((p) =>
      p.offers.map(
        (o) =>
          `  (${lit(o.id)}, ${lit(p.id)}, ${lit(o.storeId)}, ${lit(DEMO_PROVIDER_ID)}, ${lit(o.externalProductId)}, ${lit(p.variantKey)}, ` +
          `${lit(o.productUrl)}, ${lit(o.sellerName)}, ${num(o.pricePaise)}, ${num(o.originalPricePaise)}, ${lit(o.availability)}, 'demo', null)`,
      ),
    ).join(",\n") + "\non conflict do nothing;",
    "",
    "commit;",
    "",
  ];
  return lines.join("\n");
}
